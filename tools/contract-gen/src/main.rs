use sha2::{Digest, Sha256};
use std::{
    collections::BTreeMap,
    env, fs,
    path::{Path, PathBuf},
};

const VERSION: &str = "m1-controlled-generator/0.2.0";

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn render(input: &str) -> Result<BTreeMap<String, String>, String> {
    let yaml: serde_yaml::Value = serde_yaml::from_str(input).map_err(|e| e.to_string())?;
    let schemas = yaml
        .get("components")
        .and_then(|v| v.get("schemas"))
        .and_then(serde_yaml::Value::as_mapping)
        .ok_or("components.schemas missing")?;
    if schemas.len() != 42 {
        return Err(format!("expected 42 schemas, got {}", schemas.len()));
    }
    let hash = format!("{:x}", Sha256::digest(input.as_bytes()));
    let mut names = Vec::new();
    for (name, schema) in schemas {
        let name = name.as_str().ok_or("non-string schema name")?;
        let map = schema
            .as_mapping()
            .ok_or_else(|| format!("schema {name} is not a mapping"))?;
        let allowed = [
            "type",
            "pattern",
            "format",
            "enum",
            "additionalProperties",
            "required",
            "properties",
            "allOf",
            "oneOf",
            "items",
            "minimum",
            "minLength",
            "minItems",
            "uniqueItems",
            "contains",
            "minContains",
            "const",
            "description",
            "discriminator",
            "$ref",
        ];
        for key in map.keys().filter_map(serde_yaml::Value::as_str) {
            if !allowed.contains(&key) && !key.starts_with("x-") {
                return Err(format!("unknown keyword {key} in {name}"));
            }
        }
        names.push(name.to_string());
    }
    names.sort();
    let header = format!("// @generated by {VERSION}; input-sha256={hash}; DO NOT EDIT.\n");
    let mut files = BTreeMap::new();
    files.insert("metadata.rs".into(), format!("{header}pub const GENERATOR_VERSION: &str = \"{VERSION}\";\npub const INPUT_SHA256: &str = \"{hash}\";\npub const SCHEMA_COUNT: usize = 42;\n"));
    let mut types = header.clone();
    for name in &names {
        types.push_str(&format!("#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(transparent)]\npub struct {name}(pub serde_json::Value);\n\n"));
    }
    types.pop();
    files.insert("types.rs".into(), types);
    let mut schema_names = format!("{header}pub const SCHEMA_NAMES: &[&str] = &[\n");
    for name in &names {
        schema_names.push_str(&format!("    \"{name}\",\n"));
    }
    schema_names.push_str("];\n");
    files.insert("schema_names.rs".into(), schema_names);
    files.insert("mod.rs".into(), format!("{header}mod metadata;\nmod schema_names;\nmod types;\npub use metadata::*;\npub use schema_names::*;\npub use types::*;\n"));
    Ok(files)
}

fn run(base: &Path, check: bool) -> Result<(), String> {
    let input_path = base.join("docs/contracts/central-dshd-openapi.yaml");
    let out = base.join("crates/dshd-contract/src/generated");
    let rendered = render(&fs::read_to_string(&input_path).map_err(|e| e.to_string())?)?;
    if check {
        let mut drift = Vec::new();
        for (name, expected) in &rendered {
            let path = out.join(name);
            if fs::read_to_string(&path).ok().as_deref() != Some(expected) {
                drift.push(path.display().to_string());
            }
        }
        if drift.is_empty() {
            println!("RESULT=PASS ZERO_DRIFT files={}", rendered.len());
            Ok(())
        } else {
            Err(format!("generated drift: {}", drift.join(", ")))
        }
    } else {
        fs::create_dir_all(&out).map_err(|e| e.to_string())?;
        for (name, content) in rendered {
            fs::write(out.join(name), content).map_err(|e| e.to_string())?;
        }
        println!("RESULT=PASS REGENERATED schemas=42 generator={VERSION}");
        Ok(())
    }
}

fn main() {
    let mut check = None;
    let mut base = root();
    let mut args = env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = Some(true),
            "--regen" => check = Some(false),
            "--root" => base = PathBuf::from(args.next().unwrap_or_default()),
            _ => {
                eprintln!("unknown argument: {arg}");
                std::process::exit(2)
            }
        }
    }
    if let Err(e) = run(&base, check.unwrap_or(true)) {
        eprintln!("RESULT=FAIL {e}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn deterministic_and_complete() {
        let a = super::render(dshd_contract_text()).unwrap();
        let b = super::render(dshd_contract_text()).unwrap();
        assert_eq!(a, b);
        assert!(a["types.rs"].matches("pub struct ").count() == 42);
    }
    fn dshd_contract_text() -> &'static str {
        include_str!("../../../docs/contracts/central-dshd-openapi.yaml")
    }
}
